import type { TonePluginLicense } from "./types";

export type DeviceCategory =
  | "amp"
  | "cab"
  | "drive"
  | "delay"
  | "reverb"
  | "modulation"
  | "compressor"
  | "eq"
  | "pitch"
  | "synth"
  | "wah"
  | "gate"
  | "utility";

export interface Device {
  id: string;
  name: string;
  category: DeviceCategory;
  basedOn: string;
  description: string;
  tags: string[];
  /** Factory model ID confirmed for the firmware compatibility gate. */
  qcModelId?: number;
  /** Safe writable controls exposed to tone generation. */
  parameters?: readonly DeviceParameter[];
  /** False for controls that require a user-selected device resource. */
  generatable?: boolean;
  /** Licensed plugin that must be explicitly enabled for generation. */
  requiresPlugin?: TonePluginLicense;
}

export interface DeviceParameter {
  name: string;
  kind: "position" | "switch" | "text";
  /** Selects one duplicate-named ModelRepo parameter unambiguously. */
  qcParameterIndex?: number;
}

const position = (name: string): DeviceParameter => ({ name, kind: "position" });
const toggle = (name: string): DeviceParameter => ({ name, kind: "switch" });
const text = (name: string, qcParameterIndex?: number): DeviceParameter => ({
  name,
  kind: "text",
  qcParameterIndex,
});
