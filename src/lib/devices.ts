export function getDeviceListForPrompt(
  ownedPlugins: readonly TonePluginLicense[] = [],
): string {
  const enabledPlugins = new Set(ownedPlugins);
  const categories = [
    "amp",
    "cab",
    "drive",
    "delay",
    "reverb",
    "modulation",
    "compressor",
    "eq",
    "pitch",
    "synth",
    "wah",
    "gate",
  ] as DeviceCategory[];

  return categories
    .map((cat) => {
      const devices = getDevicesByCategory(cat).filter(
        (device) =>
          device.qcModelId !== undefined &&
          device.parameters !== undefined &&
          device.generatable !== false &&
          (!device.requiresPlugin || enabledPlugins.has(device.requiresPlugin)),
      );
      if (devices.length === 0) return "";
      const header = cat.toUpperCase() + "S";
      const list = devices
        .map((device) => {
          const controls = device.parameters!
            .map(
              (parameter) =>
                `${parameter.name}:${parameter.kind === "switch" ? "boolean" : parameter.kind === "text" ? "text" : "0-100"}`,
            )
            .join(", ");
          return `  - ${device.name} [id: ${device.id}] | controls: ${controls || "none"} | ${device.description}`;
        })
        .join("\n");
      return `### ${header}\n${list}`;
    })
    .filter(Boolean)
    .join("\n\n");
}
